export function getGenreNameById(id: number, mediaType: MediaType): string {
  const list = mediaType === 'movie' ? MOVIE_GENRES : TV_GENRES;
  const found = list.find((g) => g.id === id);
  if (found) return found.name;
  const fallback = [...MOVIE_GENRES, ...TV_GENRES].find((g) => g.id === id);
  return fallback?.name ?? 'Кино';
}

